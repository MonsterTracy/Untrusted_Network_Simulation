@pytest.mark.parametrize("mutation", ("run_inputs", "source", "journal", "partial_line", "symlink"))
def test_resume_bindings_and_tampering_fail_closed(tmp_path, mutation):
    ledger = GameplayLedger(tmp_path / "work", plan())
    ledger.initialize()
    if mutation == "run_inputs":
        (ledger.work / "run_inputs.json").write_bytes(b"{}")
    elif mutation == "source":
        bad = deepcopy(ledger.plan)
        bad["source"]["commit"] = "c" * 40
        bad["plan_digest"] = digest({k: v for k, v in bad.items() if k != "plan_digest"})
        with pytest.raises(ValueError):
            GameplayLedger(ledger.work, bad)
        return
    elif mutation == "journal":
        ledger.path.write_bytes(ledger.path.read_bytes().replace(b'"sequence":1', b'"sequence":2'))
    elif mutation == "partial_line":
        ledger.path.write_bytes(ledger.path.read_bytes()[:-1])
    else:
        original = ledger.path.read_bytes()
        ledger.path.unlink()
        (tmp_path / "elsewhere").write_bytes(original)
        ledger.path.symlink_to(tmp_path / "elsewhere")
    with pytest.raises(ValueError):
        recover(ledger, None, no_router)


