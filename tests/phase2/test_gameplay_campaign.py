def plan(n=2, purpose="qualification", *, paths=None, gate=None):
    source = {"commit": "a" * 40, "branch": "twd/mainline", "tracked_worktree_clean": True,
              "staged_tracked_changes": False, "source_sha256": {"fixture.py": "b" * 64}}
    game = _plan(collection_id=NAMES[purpose], ordered_seed_pool=tuple(range(100, 100 + n)),
                 target_canonical_success_count=n, source_revision=source["commit"])
    profile = {"schema_version": "phase2_router_gameplay_v1", "purpose": purpose, "campaign_id": NAMES[purpose],
        "randomized_games": n, "planning_status": "FROZEN", "qualification": None, "qualification_gate": gate,
        "paths": paths or {"plan": "/fixture/plan", "work": "/fixture/work", "destination": "/fixture/pub"},
        "excluded_game_plans": []}
    return make_plan(purpose=purpose, game_plan=game, source=source, runtime_inputs={}, exclusions=[],
                     campaign_profile=profile, qualification_gate=gate)


def no_router(*args):
    return {"triggered": False, "t1_committed": False, "t3_committed": False}


def bundle(ledger, allocation, claim, winner="Werewolf"):
    game = collection_plan_from_record(ledger.plan["game_plan"])
    _, _, evidence, replay = _fixture(game, claim, game_id=allocation["game_id"])
    old = evidence.private_replay_evidence
    private = construct_private_replay_evidence(game_id=evidence.game_id, seed=claim.seed,
        role_assignment=dict(old.role_assignment), runtime_configuration=old.runtime_configuration,
        initial_runtime_state=old.initial_runtime_state,
        replay_inputs={"fixture": "deterministic-v1", "winner": winner},
        expected_public_event_digest=old.expected_public_event_digest)
    evidence = replace(evidence, private_replay_evidence=private)
    published = publish_canonical_game_bundle(ledger.work / "games" / allocation["game_id"],
        plan=game, claim=claim, evidence=evidence, replay_executor=replay)
    return published, replay, evidence


def complete(tmp_path, n=2):
    ledger = GameplayLedger(tmp_path / "work", plan(n))
    ledger.initialize()
    for i, allocation in enumerate(ledger.plan["allocations"]):
        claim = ledger.start(allocation)
        _, replay, _ = bundle(ledger, allocation, claim, "Werewolf" if i % 2 else "Villager")
        result = verify_results(ledger, replay, no_router)[-1][1]
        ledger._append("RESULT", result)
    return ledger, replay


